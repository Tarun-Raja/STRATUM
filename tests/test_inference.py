def test_duplicate_columns(engine, record):

    frame = pd.DataFrame([record])

    frame = pd.concat([
        frame,

        frame[[engine.apc_features[0]]],
    ], axis=1)

    with pytest.raises(InputValidationError):

        engine.predict_batch(frame)


def test_empty_batch(engine):

    frame = pd.DataFrame(
        columns=engine.required_columns
    )

    with pytest.raises(InputValidationError):

        engine.predict_batch(frame)


def test_explanation_reconstruction(engine, record):

    response = engine.explain_one(
        record,
        top_n=10,
    )

    for target, evidence in (
        response["explanations"].items()
    ):

        reconstructed = (
            evidence["base_prediction"]

            + sum(
                item["contribution"]

                for item in evidence["top_features"]
            )

            + evidence["other_feature_contribution"]
        )

        np.testing.assert_allclose(
            reconstructed,

            response["records"][0][
                "predictions"
            ][target],

            rtol=1e-5,

            atol=1e-10,
        )


def test_invalid_explanation_feature_count(
    engine,
    record,
):

    with pytest.raises(InputValidationError):

        engine.explain_one(
            record,
            top_n=0,
        )


def test_json_compatibility(engine, record):

    response = engine.explain_one(
        record
    )

    encoded = json.dumps(
        response,

        allow_nan=False,
    )

    assert json.loads(encoded) == response


def test_tampered_artifact_rejected(tmp_path):

    copied_bundle = tmp_path / MODEL_VERSION

    shutil.copytree(
        BUNDLE_PATH,
        copied_bundle,
    )

    artifact = (
        copied_bundle / "thickness.joblib"
    )

    with artifact.open("ab") as handle:

        handle.write(
            b"synthetic-checksum-test"
        )

    with pytest.raises(
        ValueError,

        match="checksum mismatch",
    ):

        verify_bundle(copied_bundle)