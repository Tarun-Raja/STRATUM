
"""
STRATUM - Inference Integration Tests.

Requires a trusted model bundle and
fixture generated by Notebook 17.

Run from the STRATUM project root:

python -m pytest tests/test_inference.py -v
"""

import json
import shutil

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from ml.inference import (
    StratumInferenceEngine,
    InputValidationError,
)

from ml.model_registry import (
    read_json,
    verify_bundle,
)


PROJECT_ROOT = Path(__file__).resolve().parents[1]

ARTIFACT_ROOT = (
    PROJECT_ROOT / "ml" / "artifacts"
)

MODEL_VERSION = "1.0.0"

BUNDLE_PATH = ARTIFACT_ROOT / MODEL_VERSION

FIXTURE_PATH = (
    ARTIFACT_ROOT / "inference_fixture.json"
)


@pytest.fixture(scope="session")
def engine():

    return StratumInferenceEngine(
        BUNDLE_PATH
    )


@pytest.fixture(scope="session")
def fixture_data():

    data = read_json(FIXTURE_PATH)

    assert data["model_version"] == MODEL_VERSION

    return data


@pytest.fixture
def record(fixture_data):

    return fixture_data["inputs"].copy()


def test_model_bundle_integrity():

    manifest = verify_bundle(BUNDLE_PATH)

    assert manifest["model_version"] == MODEL_VERSION

    assert len(manifest["files"]) == 7


def test_inference_schema(engine):

    assert len(engine.apc_features) == 110

    assert len(engine.required_columns) == 111


def test_single_record_prediction(
    engine,
    record,
    fixture_data,
):

    response = engine.predict_one(record)

    assert response["record_count"] == 1

    predicted = response["records"][0]["predictions"]

    for target, expected in (
        fixture_data["expected_predictions"].items()
    ):

        assert np.isfinite(predicted[target])

        assert predicted[target] > 0

        np.testing.assert_allclose(
            predicted[target],

            expected,

            rtol=1e-10,

            atol=1e-15,
        )


def test_batch_prediction_order(engine, record):

    records = [record.copy() for _ in range(3)]

    response = engine.predict_batch(
        pd.DataFrame(records)
    )

    assert response["record_count"] == 3

    assert [
        row["row_index"]

        for row in response["records"]

    ] == [0, 1, 2]


def test_feature_column_order_independent(
    engine,
    record,
):

    reversed_record = dict(
        reversed(list(record.items()))
    )

    ordinary = engine.predict_one(record)

    reversed_result = engine.predict_one(
        reversed_record
    )

    assert ordinary == reversed_result


def test_missing_sensor_measurement(engine, record):

    record[engine.apc_features[0]] = None

    response = engine.predict_one(record)

    assert response["record_count"] == 1


def test_missing_required_column(engine, record):

    del record[engine.apc_features[0]]

    with pytest.raises(InputValidationError):

        engine.predict_one(record)


